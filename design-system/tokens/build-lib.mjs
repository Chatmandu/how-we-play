export function contrastReport(tokens) {
  const r = resolve(tokens);
  return PAIRS.map(([fg, bg, min, use]) => {
    const ratio = contrast(r[fg], r[bg]);
    return { use, fg, bg, fgHex: r[fg], bgHex: r[bg], ratio: Math.round(ratio * 100) / 100, min, pass: ratio >= min };
  });
}
