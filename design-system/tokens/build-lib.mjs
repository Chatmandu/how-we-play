// How We Play token tooling. Zero dependencies, runs in Node 18+ and in browsers.
// resolve(tokens) -> flat map { 'semantic.text.primary': '#0E1A24', ... }
// toCSS(tokens)   -> CSS custom properties (:root + diagram theme classes)
// contrast(a, b)  -> WCAG 2.x contrast ratio

export function flatten(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$')) continue;
    const path = prefix ? prefix + '.' + k : k;
    if (v && typeof v === 'object' && '$value' in v) out[path] = v.$value;
    else if (v && typeof v === 'object') flatten(v, path, out);
  }
  return out;
}

export function resolve(tokens) {
  const flat = flatten(tokens);
  const get = (p, seen = new Set()) => {
    if (seen.has(p)) throw new Error('Circular token reference: ' + p);
    seen.add(p);
    const v = flat[p];
    if (v === undefined) throw new Error('Unknown token reference: ' + p);
    return typeof v === 'string' ? v.replace(/\{([^}]+)\}/g, (_, ref) => get(ref, seen)) : v;
  };
  const out = {};
  for (const p of Object.keys(flat)) out[p] = get(p);
  return out;
}

const varName = p => '--hwp-' + p.replace(/^semantic\./, '').replace(/\./g, '-');

export function toCSS(tokens) {
  const r = resolve(tokens);
  const root = [], themes = { blue: [], light: [], mono: [] };
  for (const [p, v] of Object.entries(r)) {
    const m = p.match(/^diagram\.theme\.(blue|light|mono)\.(.+)$/);
    if (m) { themes[m[1]].push(`  --hwp-pitch-${m[2]}: ${v};`); continue; }
    root.push(`  ${varName(p)}: ${v};`);
  }
  const head = '/* GENERATED by tokens/build.mjs from tokens/tokens.json. Do not edit by hand. */\n';
  const mq = `\n@media (max-width: ${r['breakpoint.sm']}) {\n  :root {\n` +
    Object.keys(r).filter(p => /^type\.[^.]+\.size-mobile$/.test(p)).map(p => `    ${varName(p.replace(/-mobile$/, ''))}: ${r[p]};`).join('\n') + '\n  }\n}\n';
  const th = Object.entries(themes).map(([k, lines]) => `.hwp-pitch--${k} {\n${lines.join('\n')}\n}`).join('\n\n');
  return head + ':root {\n' + root.join('\n') + '\n}\n' + mq + '\n/* Diagram themes: apply to the <svg> or a wrapper */\n.hwp-pitch, ' + th.replace('.hwp-pitch--blue {', '.hwp-pitch--blue {') + '\n';
}

export function luminance(hex) {
  const n = hex.replace('#', '');
  const c = [0, 2, 4].map(i => parseInt(n.slice(i, i + 2), 16) / 255).map(v => v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}
export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
}

